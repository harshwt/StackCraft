import re
from typing import Any, Dict, List
from validator import extract_json

def _sanitize_function_name(method: str, path: str, used_names: set) -> str:
    """Generate a clean, valid, and unique Python function name from HTTP method and path."""
    # Convert {param} to by_param
    cleaned = re.sub(r"\{([a-zA-Z0-9_]+)\}", r"by_\1", path)
    # Replace non-alphanumeric chars with underscore
    cleaned = re.sub(r"[^a-zA-Z0-9_]", "_", cleaned)
    # Collapse consecutive underscores
    cleaned = re.sub(r"_+", "_", cleaned).strip("_")

    if not cleaned:
        cleaned = "root"

    # Prepend method for clarity unless already present
    method_lower = method.lower()
    if not cleaned.startswith(method_lower):
        base_name = f"{method_lower}_{cleaned}"
    else:
        base_name = cleaned

    # Ensure leading character is valid for Python identifier
    if base_name[0].isdigit():
        base_name = f"route_{base_name}"

    # Ensure uniqueness
    candidate = base_name
    counter = 1
    while candidate in used_names:
        counter += 1
        candidate = f"{base_name}_{counter}"

    used_names.add(candidate)
    return candidate

def _extract_path_params(path: str) -> List[str]:
    """Find all {param} in path."""
    return re.findall(r"\{([a-zA-Z0-9_]+)\}", path)

def generate_fastapi_code(schema_input: Any) -> str:
    """Generate executable FastAPI backend scaffold from a parsed or raw schema."""
    schema, error = extract_json(schema_input)
    if error or not schema:
        return f"# Failed to parse schema\n# {error or 'Empty schema'}"

    api_spec = schema.get("api", {})
    if not isinstance(api_spec, dict):
        api_spec = {}

    # Extract endpoints from various possible LLM formats
    raw_endpoints = api_spec.get("endpoints") or api_spec.get("routes") or []

    # If api itself has paths as keys, e.g. {"/users": {"method": "GET"}}
    if not raw_endpoints and isinstance(api_spec, dict):
        potential_paths = [k for k in api_spec.keys() if k.startswith("/")]
        if potential_paths:
            raw_endpoints = [
                {"path": p, **(api_spec[p] if isinstance(api_spec[p], dict) else {})}
                for p in potential_paths
            ]

    parsed_routes = []
    if isinstance(raw_endpoints, list):
        for item in raw_endpoints:
            if isinstance(item, str):
                parts = item.strip().split()
                if len(parts) >= 2 and parts[0].upper() in {"GET", "POST", "PUT", "DELETE", "PATCH"}:
                    method = parts[0].upper()
                    path = parts[1]
                else:
                    path = item.strip()
                    method = "POST" if any(w in path.lower() for w in ["login", "register", "create", "upload"]) else "GET"
                parsed_routes.append({"path": path, "method": method, "desc": f"{method} {path}"})
            elif isinstance(item, dict):
                path = item.get("path") or item.get("url") or item.get("endpoint") or "/"
                method = str(item.get("method", "GET")).upper()
                desc = item.get("description", f"{method} {path}")
                parsed_routes.append({"path": path, "method": method, "desc": desc})

    code_header = """from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel
from typing import Dict, Any, List, Optional

app = FastAPI(
    title="StackCraft Generated API",
    description="Automated backend scaffolding generated by StackCraft",
    version="1.0.0"
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

@app.get("/health")
def health_check() -> Dict[str, str]:
    return {"status": "healthy", "service": "stackcraft-backend"}
"""

    code_routes = []
    used_names = {"health_check"}

    for route in parsed_routes:
        path = route["path"]
        if not path.startswith("/"):
            path = f"/{path}"
        method = route["method"].lower()
        if method not in {"get", "post", "put", "delete", "patch"}:
            method = "get"

        fn_name = _sanitize_function_name(method, path, used_names)
        path_params = _extract_path_params(path)

        param_str = ", ".join([f"{p}: str" for p in path_params])

        route_code = f"""
@app.{method}("{path}")
def {fn_name}({param_str}):
    \"\"\"{route['desc']}\"\"\"
    return {{"message": "{method.upper()} {path} successful", "data": {{}}}}
"""
        code_routes.append(route_code)

    if not code_routes:
        code_routes.append("""
@app.get("/")
def root():
    return {"message": "Welcome to the StackCraft API"}
""")

    code_footer = """
if __name__ == "__main__":
    import uvicorn
    uvicorn.run(app, host="0.0.0.0", port=8000)
"""

    return code_header + "".join(code_routes) + code_footer